"""Autonomous vehicle journey risk checker.

Loads the logistic regression pipeline saved from the notebook (av_risk_model.joblib)
and scores a planned journey using only information known before departure.
"""
import altair as alt
import joblib
import numpy as np
import pandas as pd
import streamlit as st

MODEL_PATH = "av_risk_model.joblib"

st.set_page_config(page_title="AV Journey Risk Checker", page_icon="🚗", layout="centered")


@st.cache_resource
def load_bundle(path=MODEL_PATH):
    return joblib.load(path)


try:
    b = load_bundle()
except FileNotFoundError:
    st.error(f"`{MODEL_PATH}` not found. Run the save cell in your notebook and put the file next to app.py.")
    st.stop()

model, threshold = b["model"], b["threshold"]
cat_cols, num_cols, m = b["cat_cols"], b["num_cols"], b["metrics"]
roads = b["roads"].set_index("road_segment_id")
vehicles = b["vehicles"].set_index("vehicle_profile_id")

# ---------------------------------------------------------------- sidebar
with st.sidebar:
    st.header("About the model")
    st.markdown(
        f"""
**Logistic regression** trained on {len(b['ref_scores']):,} journeys, using only
pre-journey information (weather, traffic, road, vehicle).

- Cross-validated ROC AUC: **{m['cv_auc']:.3f} ± {m['cv_auc_std']:.3f}**
- Alert threshold: **{threshold:.2f}**
- At this threshold it caught **{m['recall']:.0%}** of problems on the test set,
  but only **{m['precision']:.0%}** of alerts were real problems.

**Limitations:** the model only weakly predicts individual journeys. Use it as
a screening aid that triggers closer monitoring, not to approve or cancel trips.
Only 10 vehicle profiles were available, and the data shows associations, not causes.
"""
    )

# ---------------------------------------------------------------- inputs
st.title("🚗 Autonomous Vehicle Journey Risk Checker")
st.caption("Estimates how risky a planned journey is, using only information known before departure.")

st.subheader("1. Route and vehicle")
c1, c2 = st.columns(2)
road_id = c1.selectbox(
    "Road segment", roads.index,
    format_func=lambda r: f"{r} · {roads.at[r, 'road_type']}, {roads.at[r, 'city']}")
vehicle_id = c2.selectbox(
    "Vehicle profile", vehicles.index,
    format_func=lambda v: f"{v} · {vehicles.at[v, 'sensor_suite']} suite")
uneven = c1.checkbox("Uneven road surface")

road, veh = roads.loc[road_id], vehicles.loc[vehicle_id]
with st.expander("Road and vehicle details"):
    d1, d2 = st.columns(2)
    d1.dataframe(road.astype(str).rename("Road"), width="stretch")
    d2.dataframe(veh.astype(str).rename("Vehicle"), width="stretch")

st.subheader("2. Conditions")
c3, c4 = st.columns(2)
weather = c3.selectbox("Weather", b["options"]["weather"])
traffic = c4.selectbox("Traffic level", b["options"]["traffic_level"])
time_of_day = c3.selectbox("Time of day", b["options"]["time_of_day"])
lo, hi, med = b["ranges"]["visibility_km"]
visibility = c4.slider("Visibility (km)", float(lo), float(hi), float(med), 0.1)
lo, hi, med = b["ranges"]["distance_km"]
distance = st.slider("Distance (km)", float(lo), float(hi), float(med), 0.5)

row = pd.DataFrame([{
    "weather": weather,
    "traffic_level": traffic,
    "time_of_day": time_of_day,
    "road_type": road["road_type"],
    "junction_complexity": road["junction_complexity"],
    "road_markings": road["road_markings"],
    "street_lighting": road["street_lighting"],
    "digital_infrastructure": road["digital_infrastructure"],
    "sensor_suite": veh["sensor_suite"],
    "visibility_km": visibility,
    "distance_km": distance,
    "uneven_surface": int(uneven),
    "software_version": veh["software_version"],
    "vehicle_age_months": veh["vehicle_age_months"],
    "speed_limit_mph": road["speed_limit_mph"],
}])[cat_cols + num_cols]

# ---------------------------------------------------------------- prediction
score = model.predict_proba(row)[0, 1]
ref_scores, ref_problem = b["ref_scores"], b["ref_problem"]
percentile = (ref_scores < score).mean()
# The model was trained with balanced class weights, so its score is not a calibrated
# probability. Instead, report how often past journeys with similar scores had a problem.
nearest = np.argsort(np.abs(ref_scores - score))[: max(len(ref_scores) // 10, 1)]
similar_rate = ref_problem[nearest].mean()
base_rate = ref_problem.mean()

st.subheader("3. Risk assessment")
k1, k2, k3 = st.columns(3)
k1.metric("Risk score", f"{score:.2f}", f"alert at {threshold:.2f}", delta_color="off")
k2.metric("Riskier than", f"{percentile:.0%}", "of past journeys", delta_color="off")
k3.metric("Similar past journeys", f"{similar_rate:.0%}", f"had a problem (avg {base_rate:.0%})",
          delta_color="off")

if score >= threshold:
    st.warning("**Elevated risk.** Recommend closer remote monitoring, a lower speed profile, "
               "or assigning a vehicle with a better sensor suite.")
else:
    st.success("**Below the alert threshold.** Standard monitoring. Note that the model misses "
               "some problems, so in-journey safeguards still apply.")

# ---------------------------------------------------------------- explanation
st.subheader("4. Why this score?")
prep, clf = model.named_steps["prep"], model.named_steps["clf"]
xt = prep.transform(row)
xt = xt.toarray()[0] if hasattr(xt, "toarray") else np.asarray(xt)[0]
raw_names = [n.split("__", 1)[1] for n in prep.get_feature_names_out()]


def label(name):
    for c in cat_cols:
        if name.startswith(c + "_"):
            return f"{c}: {name[len(c) + 1:]}"
    return f"{name}: {row.at[0, name]:g}"


contrib = pd.Series(xt * clf.coef_[0], index=[label(n) for n in raw_names])
contrib = contrib[contrib != 0]
top = contrib.reindex(contrib.abs().sort_values(ascending=False).index).head(8)
chart_df = pd.DataFrame({"factor": top.index, "effect": top.values,
                         "direction": np.where(top.values > 0, "Raises risk", "Lowers risk")})
chart = (alt.Chart(chart_df)
         .mark_bar()
         .encode(x=alt.X("effect:Q", title="Effect on risk (log-odds)"),
                 y=alt.Y("factor:N", sort=None, title=None),
                 color=alt.Color("direction:N",
                                 scale=alt.Scale(domain=["Raises risk", "Lowers risk"],
                                                 range=["#d62728", "#2ca02c"]),
                                 legend=alt.Legend(title=None, orient="bottom")),
                 tooltip=["factor", alt.Tooltip("effect:Q", format=".2f")]))
st.altair_chart(chart, width="stretch")
st.caption("Bars show how much each of this journey's factors pushes the score up or down. "
           "Numeric factors are measured relative to the average journey.")